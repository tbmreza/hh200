#!/usr/bin/env python3
"""Generate runnable .hhs examples and hh200-docs pages from vendored curl tests.

Reads test/curl/MANIFEST and the vendored files under test/curl/data/, then:

* writes one hh200 program per supported test to test/curl/examples/testNNN.hhs
  (the tasty curl adapter executes these files), and
* writes one Markdown example page per test to <docs>/docs/examples/curl-testNNN.md
  when an hh200-docs checkout is available.

The supported subset and the way a curl <command> becomes an hh200 request
mirror hh200/test/CurlTest/Translate.hs and the auto-skip rules in
hh200/test/CurlSpec.hs. Tests outside that subset are reported and omitted;
they are never silently turned into examples that do not run.

Usage:
    scripts/gen-curl-examples.py [--root DIR] [--docs-dir DIR] [--skip-docs]

Run directly for a docs-only refresh. scripts/sync-curl-tests.sh calls it after
vendoring fresh test data from upstream.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPLAY_HOST = "127.0.0.1"
REPLAY_PORT = 18081
DEFAULT_TAG = "curl-8_23_0"
UPSTREAM_REPO = "https://github.com/curl/curl"

HHS_MARKER = "# Generated by hh200/scripts/sync-curl-tests.sh"
DOC_MARKER = "<!-- Generated by hh200/scripts/sync-curl-tests.sh"
INDEX_BEGIN = "<!-- BEGIN curl examples (generated by hh200/scripts/sync-curl-tests.sh) -->"
INDEX_END = "<!-- END curl examples -->"

# Keep in sync with firstUnsupportedFeature / firstUnsupportedFlag in CurlSpec.hs.
UNSUPPORTED_FEATURES = {
    "SSL",
    "proxy",
    "cookies",
    "http/2",
    "http/3",
    "HTTP-auth",
    "digest",
    "NTLM",
    "GSS-API",
    "Kerberos",
    "SPNEGO",
    "libz",
    "brotli",
    "zstd",
}
UNSUPPORTED_FLAGS = {
    "-L",
    "--location",
    "--resolve",
    "-c",
    "--cookie-jar",
    "-b",
    "--cookie",
    "--tlsv1",
    "--tlsv1.0",
    "--tlsv1.1",
    "--tlsv1.2",
    "--tlsv1.3",
    "--compressed",
    "-x",
    "--proxy",
    "--cacert",
    "--cert",
    "--key",
    "-w",
    "--write-out",
    "-o",
    "--output",
    "-u",
    "--user",
    "--digest",
    "--ntlm",
}
DATA_FLAGS = {"-d", "--data", "--data-binary"}
URL_FLAGS = {"-X", "--request"}


@dataclass
class CurlTest:
    number: int
    keywords: list[str]
    name: str
    server: str
    features: list[str]
    command: str
    stdin: str | None
    reply_data: str | None
    reply_has_numbered_parts: bool
    errorcodes: list[int]

    @property
    def status(self) -> int | None:
        if self.reply_data is None:
            return None
        first = self.reply_data.splitlines()[0] if self.reply_data.splitlines() else ""
        words = first.split()
        if len(words) >= 2 and words[1].isdigit():
            return int(words[1])
        return None

    @property
    def empty_reply(self) -> bool:
        return self.reply_data is None or not self.reply_data.strip()


# ---------------------------------------------------------------------------
# curl pseudo-XML parsing (line-oriented, like test/CurlTest/Parse.hs)
# ---------------------------------------------------------------------------


def clean_comments(raw: str) -> str:
    lines = []
    for line in raw.splitlines():
        stripped = line.strip()
        if stripped.startswith("#") or stripped.startswith("<!--"):
            continue
        lines.append(line)
    return "\n".join(lines)


def section_body(text: str, name: str) -> str | None:
    """Return the body of the first <name ...>...</name>, normalized like unlines.

    Drop the newline that follows the open tag and ensure one trailing newline,
    matching the Haskell parser's `unlines body`.
    """
    match = re.search(
        rf"<{re.escape(name)}(?:\s[^>\n]*)?>(.*?)</{re.escape(name)}>",
        text,
        re.DOTALL,
    )
    if match is None:
        return None
    body = match.group(1)
    if body.startswith("\n"):
        body = body[1:]
    if body and not body.endswith("\n"):
        body += "\n"
    return body


def parse_errorcodes(verify: str) -> list[int]:
    body = section_body(verify, "errorcode")
    if body is None:
        return []
    codes: list[int] = []
    for line in body.splitlines():
        compact = re.sub(r"\s+", "", line)
        for token in compact.split(","):
            if token.isdigit():
                codes.append(int(token))
    return codes


def parse_curl_test(number: int, raw: str) -> CurlTest:
    text = clean_comments(raw)
    testcase = section_body(text, "testcase")
    if testcase is None:
        raise ValueError("missing <testcase>")

    info = section_body(testcase, "info") or ""
    reply = section_body(testcase, "reply") or ""
    client = section_body(testcase, "client") or ""
    verify = section_body(testcase, "verify") or ""

    keywords_body = section_body(info, "keywords")
    if keywords_body is None:
        raise ValueError("missing <keywords>")
    keywords = [line.strip() for line in keywords_body.splitlines()]

    server_body = section_body(client, "server")
    if server_body is None:
        raise ValueError("missing <server>")
    server = " ".join(line.strip() for line in server_body.splitlines() if line.strip())

    features_body = section_body(client, "features") or ""
    features = features_body.split()

    name_body = section_body(client, "name") or ""
    name = " ".join(line.strip() for line in name_body.splitlines() if line.strip())

    command_body = section_body(client, "command")
    if command_body is None:
        raise ValueError("missing <command>")
    command = command_body.strip()

    return CurlTest(
        number=number,
        keywords=keywords,
        name=name,
        server=server,
        features=features,
        command=command,
        stdin=section_body(client, "stdin"),
        reply_data=section_body(reply, "data"),
        reply_has_numbered_parts=re.search(r"<data\d+\b", reply) is not None,
        errorcodes=parse_errorcodes(verify),
    )


# ---------------------------------------------------------------------------
# curl <command> translation (mirrors test/CurlTest/Translate.hs)
# ---------------------------------------------------------------------------


def tokenize(command: str) -> list[str]:
    tokens: list[str] = []
    i = 0
    n = len(command)
    while i < n:
        while i < n and command[i].isspace():
            i += 1
        if i >= n:
            break
        if command[i] == '"':
            j = command.find('"', i + 1)
            if j == -1:
                tokens.append(command[i + 1 :])
                break
            tokens.append(command[i + 1 : j])
            i = j + 1
        else:
            j = i
            while j < n and not command[j].isspace():
                j += 1
            tokens.append(command[i:j])
            i = j
    return tokens


def first_after(flags: set[str], tokens: list[str]) -> str | None:
    for i, token in enumerate(tokens):
        if token in flags and i + 1 < len(tokens):
            return tokens[i + 1]
    return None


def find_url(tokens: list[str]) -> str | None:
    for token in tokens:
        if "://" in token:
            return token
    return None


def substitute(number: int, text: str) -> str:
    """Replace the curl macros used by vendored tests (test/CurlTest/Preprocess.hs)."""
    replacements = (
        ("%TESTNUMBER", str(number)),
        ("%HOSTIP", REPLAY_HOST),
        ("%HTTPPORT", str(REPLAY_PORT)),
        ("%VERSION", "0.0.1"),
        ("%CR", "\r"),
        ("%SP", " "),
        ("%TAB", "\t"),
        ("%AMP", "&"),
        ("%GT", ">"),
        ("%LT", "<"),
    )
    for macro, value in replacements:
        text = text.replace(macro, value)
    return text


def url_to_target(url: str) -> str:
    after_scheme = url.split("://", 1)[1] if "://" in url else url
    for i, char in enumerate(after_scheme):
        if char in "/?#":
            rest = after_scheme[i:]
            return "/" + rest if rest.startswith("?") else rest
    return "/"


def detect_method(tokens: list[str]) -> str:
    explicit = first_after(URL_FLAGS, tokens)
    if explicit is not None:
        return explicit
    if "-T" in tokens:
        return "PUT"
    if any(token in DATA_FLAGS or token == "--json" for token in tokens):
        return "POST"
    return "GET"


def detect_body(test: CurlTest, tokens: list[str]) -> str:
    if test.stdin is not None:
        return test.stdin
    return first_after(DATA_FLAGS, tokens) or ""


def expected_outcome(test: CurlTest) -> str:
    """Return "ok", "assert_fail", or "http_error" (same rules as CurlSpec)."""
    if test.reply_data is None:
        return "http_error"
    if test.empty_reply or any(code in (7, 52) for code in test.errorcodes):
        return "http_error"
    if test.status is not None and test.status >= 400:
        return "assert_fail"
    if 22 in test.errorcodes:
        return "assert_fail"
    return "ok"


# ---------------------------------------------------------------------------
# Skip policy (mirrors shouldSkip in CurlSpec.hs)
# ---------------------------------------------------------------------------


def skip_reason(test: CurlTest) -> str | None:
    if test.server != "http":
        return f"non-HTTP server: {test.server}"
    if test.reply_has_numbered_parts:
        return "multi-request (numbered <dataN>)"
    feature = next((f for f in test.features if f in UNSUPPORTED_FEATURES), None)
    if feature is not None:
        return f"unsupported feature: {feature}"
    flag = next((t for t in tokenize(test.command) if t in UNSUPPORTED_FLAGS), None)
    if flag is not None:
        return f"unsupported curl flag: {flag}"
    return None


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------


def upstream_url(number: int, tag: str, commit: str) -> str:
    ref = commit or tag
    return f"{UPSTREAM_REPO}/blob/{ref}/tests/data/test{number}"


def hhs_program(test: CurlTest, base_url: str, tag: str, commit: str) -> str:
    tokens = tokenize(test.command)
    url = find_url(tokens)
    if url is None:
        raise ValueError("no URL in <command>")
    method = detect_method(tokens)
    target = url_to_target(substitute(test.number, url))
    body = detect_body(test, tokens)
    outcome = expected_outcome(test)

    lines = [
        HHS_MARKER + " from curl test " + str(test.number) + "; do not edit.",
        f"# curl test {test.number}: {test.name or 'untitled'}",
        f"# Upstream: {upstream_url(test.number, tag, commit)}",
        f"# Keywords: {', '.join(test.keywords)}",
    ]
    if outcome == "http_error":
        codes = ", ".join(str(c) for c in test.errorcodes) or "empty reply"
        lines.append(
            f"# curl expects this transfer to fail (errorcode {codes}); "
            "hh200 has no response spec, so it reports the transport error."
        )
    elif outcome == "assert_fail":
        lines.append(
            "# curl --fail treats a >=400 reply as an error; asserting 200 makes "
            "hh200 fail the same way."
        )

    text = "\n".join(lines) + "\n"
    text += f"{method} {base_url}{target}\n"
    if body:
        text += body if body.endswith("\n") else body + "\n"
    if outcome != "http_error":
        text += f"HTTP {test.status if outcome == 'ok' and test.status is not None else 200}\n"
    return text


def doc_page(test: CurlTest, hhs: str, tag: str, commit: str) -> str:
    outcome = expected_outcome(test)
    codes = ", ".join(str(c) for c in test.errorcodes)
    if outcome == "ok":
        expectation = "hh200 should complete successfully."
    elif outcome == "http_error":
        expectation = (
            f"curl expects the transfer to fail (errorcode {codes or 'empty reply'}); "
            "hh200 reports the transport error."
        )
    else:
        expectation = (
            f"curl's `--fail` treats the reply as an error (errorcode {codes or '22'}); "
            "hh200's `HTTP 200` assertion fails."
        )

    keywords = ", ".join(f"`{k}`" for k in test.keywords if k)
    title = test.name or f"curl test {test.number}"
    # The page title/source line already carries the metadata; show only the
    # runnable program (plus any semantic curl notes) in the code block.
    program = "\n".join(
        line
        for line in hhs.rstrip().splitlines()
        if not line.startswith(("# Generated by", "# curl test ", "# Upstream:", "# Keywords:"))
    )
    return (
        f"{DOC_MARKER} from curl test {test.number}; do not edit. -->\n\n"
        f"# {title}\n\n"
        f"curl test [{test.number}]({upstream_url(test.number, tag, commit)})"
        + (f" — keywords: {keywords}." if keywords else ".")
        + "\n\n"
        "```sh\n"
        f"{program}\n"
        "```\n\n"
        f"{expectation}\n"
    )


def index_block(rows: list[tuple[CurlTest, str]], tag: str, commit: str) -> str:
    ref = commit or tag
    lines = [
        INDEX_BEGIN,
        "## curl conformance examples",
        "",
        f"Adapted from [curl's test suite]({UPSTREAM_REPO}/tree/{ref}/tests/data) "
        f"at `{tag}`"
        + (f" (`{commit[:12]}`)" if commit else "")
        + ". Each page shows the hh200 program that `hh200/scripts/curl-tests.sh` "
        "runs against curl's replayed response.",
        "",
    ]
    if rows:
        lines += [
            "| curl test | Example | Keywords |",
            "|---|---|---|",
        ]
        for test, slug in rows:
            name = test.name.replace("|", "\\|")
            keywords = ", ".join(test.keywords).replace("|", "\\|")
            lines.append(f"| {test.number} | [{name}]({slug}) | {keywords} |")
    else:
        lines.append("No vendored curl test is currently supported.")
    lines.append(INDEX_END)
    return "\n".join(lines) + "\n"


def update_index(path: Path, block: str) -> None:
    if path.exists():
        text = path.read_text()
    else:
        text = "# Running examples\n"
    if INDEX_BEGIN in text and INDEX_END in text:
        before, rest = text.split(INDEX_BEGIN, 1)
        _, after = rest.split(INDEX_END, 1)
        text = before.rstrip() + "\n\n" + block + after.lstrip("\n")
    else:
        text = text.rstrip() + "\n\n" + block
    if not text.endswith("\n"):
        text += "\n"
    path.write_text(text)


def remove_stale(directory: Path, pattern: str, marker: str, keep: set[str]) -> None:
    if not directory.is_dir():
        return
    for path in directory.glob(pattern):
        if path.name in keep:
            continue
        try:
            generated = path.read_text().startswith(marker)
        except OSError:
            continue
        if generated:
            path.unlink()


def manifest_numbers(path: Path) -> list[int]:
    numbers: list[int] = []
    for line in path.read_text().splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        numbers.append(int(stripped))
    return numbers


def read_upstream(path: Path) -> tuple[str, str]:
    tag = DEFAULT_TAG
    commit = ""
    if not path.exists():
        return tag, commit
    for line in path.read_text().splitlines():
        if line.startswith("tag:"):
            tag = line.split(":", 1)[1].strip()
        elif line.startswith("commit:"):
            commit = line.split(":", 1)[1].strip()
    return tag, commit


def main(argv: list[str]) -> int:
    default_root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=default_root, help="hh200 repo root")
    parser.add_argument(
        "--docs-dir",
        type=Path,
        default=default_root.parent / "hh200-docs",
        help="hh200-docs checkout (default: sibling of the hh200 repo)",
    )
    parser.add_argument("--skip-docs", action="store_true", help="do not write doc pages")
    args = parser.parse_args(argv)

    root: Path = args.root.resolve()
    curl_dir = root / "test" / "curl"
    manifest = curl_dir / "MANIFEST"
    data_dir = curl_dir / "data"
    examples_dir = curl_dir / "examples"

    if not manifest.exists():
        print(f"error: {manifest} not found", file=sys.stderr)
        return 1

    tag, commit = read_upstream(curl_dir / "UPSTREAM")
    base_url = f"http://{REPLAY_HOST}:{REPLAY_PORT}"

    docs_dir: Path | None = None
    if not args.skip_docs:
        docs_dir = args.docs_dir.resolve()
        if not (docs_dir / "docs").is_dir():
            print(
                f"warning: {docs_dir} is not an hh200-docs checkout; skipping doc pages",
                file=sys.stderr,
            )
            docs_dir = None

    examples_dir.mkdir(parents=True, exist_ok=True)
    docs_examples: Path | None = None
    if docs_dir is not None:
        docs_examples = docs_dir / "docs" / "examples"
        docs_examples.mkdir(parents=True, exist_ok=True)

    written: list[tuple[CurlTest, str]] = []
    kept_hhs: set[str] = set()
    for number in manifest_numbers(manifest):
        path = data_dir / f"test{number}"
        if not path.exists():
            print(f"warning: test{number} not vendored, skipping", file=sys.stderr)
            continue
        try:
            test = parse_curl_test(number, path.read_text())
        except ValueError as exc:
            print(f"error: test{number}: {exc}", file=sys.stderr)
            return 1
        reason = skip_reason(test)
        if reason is not None:
            print(f"  - test{number}: {reason}", file=sys.stderr)
            continue
        try:
            hhs = hhs_program(test, base_url, tag, commit)
        except ValueError as exc:
            print(f"error: test{number}: {exc}", file=sys.stderr)
            return 1

        hhs_name = f"test{number}.hhs"
        (examples_dir / hhs_name).write_text(hhs)
        kept_hhs.add(hhs_name)
        written.append((test, f"curl-test{number:03d}.md"))
        print(f"  + test{number}", file=sys.stderr)

    remove_stale(examples_dir, "test*.hhs", HHS_MARKER, kept_hhs)

    if docs_examples is not None:
        kept_docs: set[str] = set()
        for test, slug in written:
            hhs = (examples_dir / f"test{test.number}.hhs").read_text()
            (docs_examples / slug).write_text(doc_page(test, hhs, tag, commit))
            kept_docs.add(slug)
        remove_stale(docs_examples, "curl-test*.md", DOC_MARKER, kept_docs)
        update_index(
            docs_examples / "index.md",
            index_block(written, tag, commit),
        )

    print(
        f"==> wrote {len(written)} hh200 example(s) to {examples_dir}",
        file=sys.stderr,
    )
    if docs_examples is not None:
        print(f"==> synced examples to {docs_examples}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
